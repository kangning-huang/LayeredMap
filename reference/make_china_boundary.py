"""Write crates/lm-profile/src/china_boundary.rs: a simplified mainland-China boundary.

Source: Natural Earth 1:50m admin-0 countries (public domain), the feature whose ADMIN is
'China'. In Natural Earth that unit is the mainland plus Hainan and other islands; Taiwan,
Hong Kong and Macau are separate admin-0 units and are therefore NOT included.

Processing (deterministic): keep parts larger than 0.5 square degrees (the mainland and Hainan),
buffer outwards by 0.1 degrees (so coastal points are not lost to the simplification), simplify
with a 0.12-degree tolerance, round to 0.01 degrees. The result is used only to decide whether
points lie in mainland China (Assumption catalog > China offsets); it is not drawn.

Run once, by hand (it needs the Natural Earth zip, which is not committed):
  curl -LO https://naciscdn.org/naturalearth/50m/cultural/ne_50m_admin_0_countries.zip
  mamba run -n layeredmap-ref python -I reference/make_china_boundary.py ne_50m_admin_0_countries.zip
"""

from __future__ import annotations

import sys
from pathlib import Path

import geopandas as gpd
from shapely.geometry import MultiPolygon, Polygon
from shapely.ops import unary_union

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "crates" / "lm-profile" / "src" / "china_boundary.rs"


def main(zip_path: str) -> None:
    df = gpd.read_file(f"zip://{Path(zip_path).resolve()}")
    china = df[df["ADMIN"] == "China"].geometry.iloc[0]
    parts = list(china.geoms) if isinstance(china, MultiPolygon) else [china]
    parts = [p for p in parts if p.area > 0.5]
    shape = unary_union(parts).buffer(0.1, join_style="mitre").simplify(0.12, preserve_topology=True)
    polys = list(shape.geoms) if isinstance(shape, MultiPolygon) else [shape]
    polys.sort(key=lambda p: -p.area)
    lines = [
        "//! A simplified mainland-China boundary (generated by `reference/make_china_boundary.py`; do",
        "//! not edit). Natural Earth 1:50m admin-0 'China' (public domain): the mainland and Hainan,",
        "//! without Taiwan, Hong Kong and Macau; buffered outwards by 0.1 degrees and simplified.",
        "//! Each part is an outer ring of (longitude, latitude) pairs; the first point is not repeated.",
        "",
        "#[rustfmt::skip]",
        "pub(crate) const CHINA_PARTS: &[&[(f32, f32)]] = &[",
    ]
    total = 0
    for p in polys:
        assert isinstance(p, Polygon)
        ring = list(p.exterior.coords)[:-1]
        total += len(ring)
        lines.append("    &[")
        row = []
        for x, y in ring:
            row.append(f"({x:.2f}, {y:.2f})")
            if len(row) == 6:
                lines.append("        " + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("        " + ", ".join(row) + ",")
        lines.append("    ],")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(polys)} parts, {total} vertices -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
