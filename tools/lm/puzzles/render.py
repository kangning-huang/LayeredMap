"""Writes docs/lm/puzzles/puzzles.md from docs/lm/puzzles/puzzles.json.

    python -I tools/lm/puzzles/render.py docs/lm/puzzles/puzzles.json docs/lm/puzzles/puzzles.md

Run after `solve.py --update`, so the verification numbers in the page are the solver's.
"""

import json
import sys
from pathlib import Path


def num(v, unit):
    if abs(v) >= 1e6:
        s = f"{v / 1e6:g} million"
    elif abs(v) >= 1000:
        s = f"{v:,.0f}"
    else:
        s = f"{v:g}"
    return f"{s} {unit}".strip()


def robustness_line(name, r):
    lo, hi = num(r["holds_from"], r["unit"]), num(r["holds_to"], r["unit"])
    more = " or beyond" if r["capped"] else ""
    return f"`{name}` = {num(r['value'], r['unit'])}: same answer from {lo} to {hi}{more}"


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    doc = json.loads(src.read_text())
    ds = doc["datasets"]
    new = doc["new_actions"]
    out = []
    w = out.append
    w("# LayeredMap Pro puzzles")
    w("")
    w("Eight original \"where is it?\" puzzles for testing LayeredMap Pro end to end and for the release")
    w("videos. Each is solved by a plan of LayeredMap actions; actions marked **new** are the proposals in")
    w("[mechanics.md](mechanics.md). Every answer was checked by the reference solver")
    w("`tools/lm/puzzles/solve.py` on the open datasets described in")
    w(f"`{doc['data_readme']}`, which also printed the candidate counts and robustness")
    w("ranges below. The machine-readable version is [puzzles.json](puzzles.json); answer geometries")
    w("are in [answers.geojson](answers.geojson). This page is generated by `tools/lm/puzzles/render.py`.")
    w("")
    w("| # | Title | Difficulty | Setting | Answer | Candidates after each clue | New actions |")
    w("|---|---|---|---|---|---|---|")
    for p in doc["puzzles"]:
        v = p.get("verification", {})
        counts = " → ".join(f"{c:,}" for c in v.get("candidates_after_each_clue", []))
        news = sorted({s["action"] for s in p["plan"] if s["new"]})
        w(
            f"| {p['id']} | {p['title']} | {p['difficulty']} | {p['setting']} | {p['answer']['name']} | "
            f"{counts} | {', '.join(news) or 'none'} |"
        )
    w("")
    w("How to reproduce: `python -I tools/lm/puzzles/solve.py` in the `layeredmap-ref` environment")
    w("(add `--update docs/lm/puzzles/puzzles.json --answers docs/lm/puzzles/answers.geojson` to refresh")
    w("the files, then run this renderer). The solver's method and tolerances are in its docstring.")
    w("Robustness: each threshold was moved alone, in fixed steps, until the answer changed or")
    w("stopped being unique; \"or beyond\" means the answer still held at the last step tried (8 steps).")
    w("")
    w("Credits for the data: WorldClim 2.1 (Fick and Hijmans 2017, CC BY 4.0); Natural Earth (public")
    w("domain); GEM Global Active Faults (Styron and Pagani 2020, CC BY-SA 4.0).")
    for p in doc["puzzles"]:
        a = p["answer"]
        v = p.get("verification", {})
        w("")
        w(f"## {p['id']} · {p['title']}")
        w("")
        diff = p["difficulty"] + (f" ({p['difficulty_note']})" if p.get("difficulty_note") else "")
        w(f"**Difficulty:** {diff}. **Setting:** {p['setting']}. **Answer type:** {p['answer_kind']}.")
        w("")
        w(p["story"])
        w("")
        w("**Clues**")
        w("")
        for i, c in enumerate(p["clues"], 1):
            w(f"{i}. {c}")
        w("")
        w("**What the user types into Pro**")
        w("")
        w(f"- English: \"{p['request']['en']}\"")
        if "zh" in p["request"]:
            w(f"- 中文：“{p['request']['zh']}”")
        w("")
        w("**Datasets:** " + "; ".join(ds[d]["name"] for d in p["datasets"]) + ".")
        w("")
        w("**Expected plan**")
        w("")
        w("| Step | Action | On | Detail |")
        w("|---|---|---|---|")
        for i, s in enumerate(p["plan"], 1):
            act = f"`{s['action']}`" + (f" **new** ({new[s['action']].split(' ', 1)[0]})" if s["new"] else "")
            w(f"| {i} | {act} | {s['on']} | {s['detail']} |")
        w("")
        lat, lon = a["lat"], a["lon"]
        ns, ew = ("N" if lat >= 0 else "S"), ("E" if lon >= 0 else "W")
        w(
            f"**Answer:** {a['name']} ({a['name_zh']}), {a['country']}: {abs(lat):.3f}° {ns}, "
            f"{abs(lon):.3f}° {ew}. {a['note']}"
        )
        if a.get("town"):
            w(f"Town: {a['town']}.")
        w("")
        w("**Verification**")
        w("")
        if v:
            status = "verified: unique answer" if v["verified"] else "NOT VERIFIED"
            w(f"Solver result: {status}.")
            w("")
            w("| Clue | Solver test | Candidates left |")
            w("|---|---|---|")
            for i, (t, n) in enumerate(zip(v["solver_tests"], v["candidates_after_each_clue"]), 1):
                w(f"| {i} | {t} | {n:,} |")
            w("")
            f = v["found"][0]
            facts = {k: f[k] for k in f if k not in ("name", "lat", "lon", "country", "towns_inside")}
            w("Values at the answer: " + ", ".join(f"{k} {val}" for k, val in facts.items()) + ".")
            if f.get("towns_inside"):
                w("Towns inside the area: " + ", ".join(f["towns_inside"]) + ".")
            w("")
            w("Robustness (each threshold moved alone):")
            w("")
            for k, r in v["robustness"].items():
                w(f"- {robustness_line(k, r)}")
        if p.get("verification_note"):
            w("")
            w(p["verification_note"])
    dst.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
