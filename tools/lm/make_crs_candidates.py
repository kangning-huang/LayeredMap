"""Writes crates/lm-profile/src/crs_candidates.rs: the coordinate systems "Where should this data
be?" (WP2.4) tries, with their areas of use. Read from the crs-definitions crate's EPSG table
(the same definitions the engine converts with), so every candidate can be converted.

Usage: python3 tools/lm/make_crs_candidates.py <path to crs-definitions-*/src/defs.rs>
"""
import re, sys, pathlib

defs = pathlib.Path(sys.argv[1]).read_text()
rows = []
for line in defs.splitlines():
    m = re.match(r'EPSG_(\d+)\|(\d+)\|"([^"]*)"\|r#"PROJCS\["([^"]+)"', line)
    if not m:
        continue
    code, proj4, name = int(m.group(2)), m.group(3), m.group(4)
    lon0 = re.search(r"\+lon_0=(-?[\d.]+)", proj4)
    lon0 = float(lon0.group(1)) if lon0 else None
    zone = re.search(r"\+zone=(\d+)", proj4)
    if lon0 is None and zone:
        lon0 = int(zone.group(1)) * 6 - 183.0
    if code > 65535 or lon0 is None:
        continue
    area = None
    if re.fullmatch(r"WGS 84 / UTM zone \d+[NS]", name):
        south = name.endswith("S")
        area = (lon0 - 3, -80.0 if south else 0.0, lon0 + 3, 0.0 if south else 84.0)
    elif re.fullmatch(r"(CGCS2000|Xian 1980|Beijing 1954) / (3-degree )?Gauss-Kruger (zone \d+|CM \d+E)", name):
        half = 1.5 if "3-degree" in name else 3.0
        area = (lon0 - half, 16.0, lon0 + half, 54.0)
    if area:
        rows.append((code, name, area))

# A few national grids with their areas of use (EPSG bounding boxes, rounded outward).
national = {
    27700: (-9.0, 49.75, 2.01, 61.01),   # OSGB36 / British National Grid
    2154: (-9.86, 41.15, 10.38, 51.56),  # RGF93 / Lambert-93
    28992: (3.2, 50.75, 7.22, 53.7),     # Amersfoort / RD New
    3006: (10.03, 54.96, 24.17, 69.07),  # SWEREF99 TM
    2193: (166.37, -47.33, 178.63, -34.1),  # NZGD2000 / New Zealand Transverse Mercator
    3414: (103.59, 1.13, 104.07, 1.47),  # SVY21 / Singapore TM
    2326: (113.76, 22.13, 114.51, 22.58),  # Hong Kong 1980 Grid System
}
for code, area in national.items():
    m = re.search(rf'EPSG_{code}\|{code}\|"[^"]*"\|r#"PROJCS\["([^"]+)"', defs)
    if m:
        rows.append((code, m.group(1), area))

rows.sort()
out = ["//! The coordinate systems \"Where should this data be?\" tries (WP2.4), with their areas of",
       "//! use (west, south, east, north in degrees). Generated by tools/lm/make_crs_candidates.py from",
       "//! the crs-definitions EPSG table; do not edit by hand.",
       "",
       "/// (EPSG code, name, area of use).",
       f"pub static CANDIDATES: [(u16, &str, [f64; 4]); {len(rows)}] = ["]
for code, name, (w, s, e, n) in rows:
    out.append(f'    ({code}, "{name}", [{w:.2f}, {s:.2f}, {e:.2f}, {n:.2f}]),')
out.append("];")
pathlib.Path("crates/lm-profile/src/crs_candidates.rs").write_text("\n".join(out) + "\n")
print(len(rows), "candidates")
